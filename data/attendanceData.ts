export function calculateAttendanceMetrics(records: AttendanceRecord[]): AttendanceMetrics {
  const totalLoggedSessions = new Set(records.map((r) => r.sessionId || `${r.date}-${r.batchCode}`)).size;
  
  // Calculate distinct hours per session type
  let theoryHours = 0;
  let practicalHours = 0;
  let onsiteHours = 0;

  // Track unique session/type hours to avoid duplicating per student
  const sessionTypeMap = new Map<string, { duration: number; type: "T" | "P" | "O" }>();
  
  records.forEach((rec) => {
    const key = `${rec.date}_${rec.batchCode}_${rec.topic}_${rec.type}`;
    if (!sessionTypeMap.has(key)) {
      sessionTypeMap.set(key, { duration: rec.duration, type: rec.type });
    }
  });

  sessionTypeMap.forEach(({ duration, type }) => {
    if (type === "T") theoryHours += duration;
    else if (type === "P") practicalHours += duration;
    else if (type === "O") onsiteHours += duration;
  });

  const totalLoggedHours = theoryHours + practicalHours + onsiteHours;

  const presentCount = records.filter((r) => r.status === "Present").length;
  const lateCount = records.filter((r) => r.status === "Late").length;
  const absentCount = records.filter((r) => r.status === "Absent").length;
  const totalMarks = records.length;

  const overallAttendanceRate =
    totalMarks > 0 ? Math.round(((presentCount + lateCount * 0.75) / totalMarks) * 100) : 0;

  const uniqueStudents = new Set(records.map((r) => r.studentId)).size;

  return {
    totalLoggedSessions,
    totalLoggedHours,
    theoryHours,
    practicalHours,
    onsiteHours,
    overallAttendanceRate,
    totalStudentsTracked: uniqueStudents,
    presentMarksCount: presentCount,
    absentMarksCount: absentCount,
    lateMarksCount: lateCount,
  };
}
